-- Migration 013: единицы bonds_catalog.ytm — проценты годовых (задача 005.4, P-E).
--
-- ДО миграции колонка хранила ДОЛЮ единицы (0.24 = 24.01%), тогда как всё
-- остальное в проекте — в ПРОЦЕНТАХ: coupon_rate_percent и real_yield_percent
-- в каталоге, флаги --min-ytm/--max-ytm CLI, вывод calculate-ytm/rebalance-report
-- (ytm_pct), тесты export-portfolio md (заголовок «YTM, %»). Любой потребитель,
-- смешавший SQL-колонку с выводом CLI, молча ошибался в 100 раз (кейсы каталога:
-- Сэтл 002P-04 — 0.24 при реальных 24.01%, ЛСР — 0.17 = 17.41%, Монополия
-- 001P-06 — 10.04 = 1004% дистресса); export-portfolio md печатал долю под
-- заголовком «YTM, %» как есть.
--
-- Решение (вариант «миграция» из задачи 005.4 — «чище» конвенции): хранить
-- проценты везде. Расчётный движок (src/services/cashflow.py,
-- calculate_bond_cashflow_metrics) внутри работает с долей — это внутренний
-- контракт; единственный писатель колонки update_bonds_derived_metrics
-- (src/storage.py) умножает на 100 на границе записи. Читатели
-- (calculate-ytm/rebalance-report через _enrich_bonds_with_ytm) берут значение
-- как есть. Канонический вывод тулкита не меняется: проценты, как и было.
--
-- ПОРЯДОК ВНЕДРЕНИЯ: применить миграцию ДО первого запуска кода с новым
-- писателем (обновление каталога/цен). Если новый код уже писал проценты до
-- применения миграции — полная чистка достигается одним прогоном
-- `python main.py update-bonds --recalculate-derived-metrics` (писатель
-- пересчитает все значения в правильных единицах).
--
-- ИДЕМПОТЕНТНОСТЬ: умножение на 100 само по себе повторонебезопасно, поэтому
-- конверсия защищена стражем по таблице учёта версий: повторный ручный прогон
-- файла (мимо ранера) по уже сконвертированной базе ничего не меняет. NULL не
-- трогаем (осознанный NULL с ytm_null_reason остаётся NULL). COMMENT — идемпотентен
-- по природе; schema_migrations создаётся ранером до применения миграций.

UPDATE bonds_catalog
SET ytm = ytm * 100
WHERE ytm IS NOT NULL
  AND NOT EXISTS (
      SELECT 1 FROM schema_migrations WHERE version = 13
  );

-- Конвенция единиц — прямо в схеме, чтобы её видел любой ad-hoc SQL-потребитель.
COMMENT ON COLUMN bonds_catalog.ytm IS
    'Доходность к погашению, проценты годовых (24.01 = 24.01%). '
    'Расчётный движок cashflow.py возвращает долю — писатель update_bonds_derived_metrics '
    'умножает на 100 (задача 005.4, миграция 013). До миграции 013 хранилась доля.';
